function makeTownMap() {
	const w = 40;
	const h = 24;
	const rows = Array.from({ length: h }, (_, y) =>
		Array.from({ length: w }, (_, x) => (x === 0 || y === 0 || x === w - 1 || y === h - 1 ? "T" : ".")),
	);
	rows[8][20] = "P";
	rows[12][20] = "W";
	return rows.map((row) => row.join(""));
}

